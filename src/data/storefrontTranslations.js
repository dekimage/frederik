export function translateStorefront(text, language) {
  if (language !== "nl" || typeof text !== "string") return text;
  if (storefrontNl[text]) return storefrontNl[text];
  if (/^Product .* (does not exist\.|is not currently available\.)$/.test(text))
    return "Deze afdruk is momenteel niet beschikbaar. Controleer je winkelwagen.";
  if (text.startsWith("Maximum ") && text.endsWith(" items per order."))
    return text
      .replace("Maximum ", "Maximaal ")
      .replace(" items per order.", " artikelen per bestelling.");
  return text;
}
